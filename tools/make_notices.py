"""Gives every TF3OpenAPI mod in mod/ its notice: content/gui/tf3api_notice/notice.script.lua + notice.res.lua, from
the template converter/notice.script.lua (the converter writes the same into converted mods). In the game the notice
opens one window when TF3OpenAPI's native layer is not running, naming the mods that need it.

Run from the repository root after changing the template or adding a mod:
    python tools/make_notices.py
"""
import json
import os
import re

from PIL import Image, ImageDraw, ImageFont

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
template = open(os.path.join(root, 'converter', 'notice.script.lua'), encoding='utf-8').read()


def lua_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


RES = '''-- Mounts the TF3OpenAPI notice in the game bar (it draws nothing there; it opens a window when something is missing).
function data()
	return {
		type = "react-plugin ::GameBarInfoDisplayExtension",
		data = {
			filePath = "%s::/gui/tf3api_notice/notice.script@Host",
			priority = 10,
		}
	}
end
'''

# The mod list's Source icons, as raw pixels (RGBA, 64 x 64) for the native layer: the source cell is given these
# bytes directly, so it never depends on a mod's files being mounted. The pictures are in tools/source_icons
# (cut from the logo set by the author): TF3OpenAPI's own folder ("API"), one for each game a converted mod is
# from, and "TF3" in place of the game's own icon for the mods that come with the game (source "BuiltInMods").
ICON_SIZE = 64
SOURCES = [
    ('TF3OpenAPI', 'TF3OpenAPI', 'api'),
    ('TF3OpenAPI-TrF', 'Train Fever (converted by TF3OpenAPI)', 'trf'),
    ('TF3OpenAPI-TF1', 'Transport Fever (converted by TF3OpenAPI)', 'tf1'),
    ('TF3OpenAPI-TF2', 'Transport Fever 2 (converted by TF3OpenAPI)', 'tf2'),
    ('BuiltInMods', 'Built-In', 'tf3'),
]
# the gold logo for the DLC that comes with the game, used when tools/source_icons/dlc.png is there
if os.path.isfile(os.path.join(root, 'tools', 'source_icons', 'dlc.png')):
    SOURCES.append(('DLC', 'DLC', 'dlc'))


def icon_hex(picture):
    image = Image.open(os.path.join(root, 'tools', 'source_icons', picture + '.png')).convert('RGBA').resize((ICON_SIZE, ICON_SIZE), Image.LANCZOS)
    rows = []
    for y in range(ICON_SIZE - 1, -1, -1):   # the game's ImageView shows these bytes upside down: bottom row first
        rows.append(b''.join(bytes(image.getpixel((x, y))) for x in range(ICON_SIZE)))
    return b''.join(rows).hex()


def literal(text):
    return 'R"HEX(' + text + ')HEX",\n'


with open(os.path.join(root, 'native', 'src', 'source_icon.inc'), 'w', newline='\n') as handle:
    handle.write('// Generated by tools/make_notices.py: the mod list source icons (64 x 64 RGBA as hex) and titles, as Lua, in\n')
    handle.write('// pieces (a compiler holds only about 16 KB in one string literal); the pieces are joined in this order.\n')
    handle.write(literal('local ICONS = {\n'))
    for name, title, picture in SOURCES:
        hex_text = icon_hex(picture)
        handle.write(literal('\t[%s] = { title = %s, size = %d, hex = ""' % (lua_string(name), lua_string(title), ICON_SIZE)))
        for k in range(0, len(hex_text), 12000):
            handle.write(literal(' .. "' + hex_text[k:k + 12000] + '"'))
        handle.write(literal(' },\n'))
    handle.write(literal('}\n'))

for mod in sorted(os.listdir(os.path.join(root, 'mod'))):
    folder = os.path.join(root, 'mod', mod)
    info_path = os.path.join(folder, 'mod.json')
    if not mod.startswith('tf3api_') or not os.path.isfile(info_path):
        continue
    info = json.load(open(info_path, encoding='utf-8'))
    values = {
        '@MOD_ID@': lua_string(mod), '@MOD_NAME@': lua_string(info.get('name') or mod), '@KIND@': lua_string('api'),
        '@FOLDER@': lua_string(''), '@WRITER@': 'written by tools/make_notices.py',
    }
    text = re.sub(r'@[A-Z_]+@', lambda m: values[m.group(0)], template)
    out = os.path.join(folder, 'content', 'gui', 'tf3api_notice')
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, 'notice.script.lua'), 'w', encoding='utf-8', newline='\n').write(text)
    open(os.path.join(out, 'notice.res.lua'), 'w', encoding='utf-8', newline='\n').write(RES % mod)
    # a mod with a _content.json lists its files there: the game reads only those
    listing = os.path.join(folder, '_content.json')
    if os.path.isfile(listing):
        content = json.load(open(listing, encoding='utf-8'))
        files = content.get('files') or []
        for name in ('gui/tf3api_notice/notice.res.lua', 'gui/tf3api_notice/notice.script.lua'):
            if name not in files:
                files.append(name)
        content['files'] = sorted(files)
        open(listing, 'w', encoding='utf-8', newline='\n').write(json.dumps(content, indent=4) + '\n')
    print(mod + ': notice written')
