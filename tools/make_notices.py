"""Gives every TF3OpenAPI mod in mod/ its notice: content/gui/tf3api_notice/notice.script.lua + notice.res.lua, from
the template converter/notice.script.lua (the converter writes the same into converted mods). In the game the notice
opens one window when TF3OpenAPI's native layer is not running, naming the mods that need it.

Run from the repository root after changing the template or adding a mod:
    python tools/make_notices.py
"""
import json
import os
import re
import struct

from PIL import Image, ImageDraw, ImageFont

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
template = open(os.path.join(root, 'converter', 'notice.script.lua'), encoding='utf-8').read()


def lua_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


RES = '''-- Mounts the TF3OpenAPI notice in the game bar (it draws nothing there; it opens a window when something is missing).
function data()
	return {
		type = "react-plugin ::GameBarInfoDisplayExtension",
		data = {
			filePath = "%s::/gui/tf3api_notice/notice.script@Host",
			priority = 10,
		}
	}
end
'''

def source_icon(size, text='API', colour=(33, 107, 219), scale_of_text=0.40):
    """A mod list Source icon: a coloured rounded square with a short text in Isotherm Sans Bold, as a 32-bit .tga in
    the form the game's own icons have (bottom-up, 8 alpha bits)."""
    scale = 8
    big = size * scale
    image = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((scale, scale, big - scale - 1, big - scale - 1), radius=big // 5, fill=colour + (255,))
    font_path = os.path.join(root, 'native', 'third_party', 'isotherm_sans', 'IsothermSans-Bold.ttf')
    font = ImageFont.truetype(font_path, int(big * scale_of_text))
    box = draw.textbbox((0, 0), text, font=font)
    draw.text(((big - (box[2] - box[0])) / 2 - box[0], (big - (box[3] - box[1])) / 2 - box[1]), text, font=font, fill=(255, 255, 255, 255))
    image = image.resize((size, size), Image.LANCZOS)
    rows = []
    for y in range(size - 1, -1, -1):
        for x in range(size):
            r, g, b, a = image.getpixel((x, y))
            rows.append(bytes((b, g, r, a)))
    return struct.pack('<BBBHHBHHHHBB', 0, 0, 2, 0, 0, 0, 0, 0, size, size, 32, 8) + b''.join(rows)


# The source icons as raw pixels (RGBA, 32 x 32) for the native layer: the mod list's source cell is given these
# bytes directly, so it never depends on a mod's files being mounted. The folder of TF3OpenAPI's own mods ("API")
# and one folder for each game a converted mod is from.
SOURCES = [
    ('TF3OpenAPI', 'TF3OpenAPI', 'API', (33, 107, 219), 0.40),
    ('TF3OpenAPI-TrF', 'Train Fever (converted by TF3OpenAPI)', 'TrF', (176, 58, 46), 0.34),
    ('TF3OpenAPI-TF1', 'Transport Fever (converted by TF3OpenAPI)', 'TF1', (39, 144, 92), 0.34),
    ('TF3OpenAPI-TF2', 'Transport Fever 2 (converted by TF3OpenAPI)', 'TF2', (214, 126, 24), 0.34),
]


def icon_hex(text, colour, text_scale):
    data = source_icon(32, text, colour, text_scale)[18:]
    out = bytearray()
    for row in [data[y * 128:(y + 1) * 128] for y in range(32)][::-1]:   # the .tga is bottom-up
        for x in range(32):
            b_, g, r, a_ = row[x * 4:x * 4 + 4]
            out += bytes((r, g, b_, a_))
    # the game's ImageView shows these bytes upside down (seen in the mod list), so the rows go in bottom first
    rows_out = [bytes(out[y * 128:(y + 1) * 128]) for y in range(32)][::-1]
    return b''.join(rows_out).hex()


with open(os.path.join(root, 'native', 'src', 'source_icon.inc'), 'w', newline='\n') as handle:
    handle.write('// Generated by tools/make_notices.py: the mod list source icons (32 x 32 RGBA as hex) and titles, as Lua.\n')
    # one string literal for each icon: a compiler holds only about 16 KB in one
    handle.write('R"HEX(local ICONS = {\n)HEX"\n')
    for name, title, text, colour, text_scale in SOURCES:
        handle.write('R"HEX(\t[%s] = { title = %s, hex = %s },\n)HEX"\n' % (lua_string(name), lua_string(title), lua_string(icon_hex(text, colour, text_scale))))
    handle.write('R"HEX(}\n)HEX"\n')

for mod in sorted(os.listdir(os.path.join(root, 'mod'))):
    folder = os.path.join(root, 'mod', mod)
    info_path = os.path.join(folder, 'mod.json')
    if not mod.startswith('tf3api_') or not os.path.isfile(info_path):
        continue
    info = json.load(open(info_path, encoding='utf-8'))
    values = {
        '@MOD_ID@': lua_string(mod), '@MOD_NAME@': lua_string(info.get('name') or mod), '@KIND@': lua_string('api'),
        '@FOLDER@': lua_string(''), '@WRITER@': 'written by tools/make_notices.py',
    }
    text = re.sub(r'@[A-Z_]+@', lambda m: values[m.group(0)], template)
    out = os.path.join(folder, 'content', 'gui', 'tf3api_notice')
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, 'notice.script.lua'), 'w', encoding='utf-8', newline='\n').write(text)
    open(os.path.join(out, 'notice.res.lua'), 'w', encoding='utf-8', newline='\n').write(RES % mod)
    # a mod with a _content.json lists its files there: the game reads only those
    listing = os.path.join(folder, '_content.json')
    if os.path.isfile(listing):
        content = json.load(open(listing, encoding='utf-8'))
        files = content.get('files') or []
        for name in ('gui/tf3api_notice/notice.res.lua', 'gui/tf3api_notice/notice.script.lua'):
            if name not in files:
                files.append(name)
        content['files'] = sorted(files)
        open(listing, 'w', encoding='utf-8', newline='\n').write(json.dumps(content, indent=4) + '\n')
    print(mod + ': notice written')
