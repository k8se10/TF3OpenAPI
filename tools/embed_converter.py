"""Writes converter/convert.lua and converter/station_shim.lua into native/src/*.inc as byte arrays for the DLL.

Run from the repository root after changing either file:
    python tools/embed_converter.py
"""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
for source, target in (('convert.lua', 'convert_lua.inc'), ('station_shim.lua', 'station_shim_lua.inc')):
    data = open(os.path.join(root, 'converter', source), 'rb').read().replace(b'\r\n', b'\n')
    lines = ['// Generated by tools/embed_converter.py from converter/%s. Do not edit.' % source]
    for i in range(0, len(data), 24):
        lines.append(','.join(str(b) for b in data[i:i + 24]) + ',')
    open(os.path.join(root, 'native', 'src', target), 'w', newline='\n').write('\n'.join(lines) + '\n')
    print(target + ':', len(data), 'bytes')
