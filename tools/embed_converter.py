"""Writes converter/convert.lua into native/src/convert_lua.inc as a byte array for the DLL.

Run from the repository root after changing convert.lua:
    python tools/embed_converter.py
"""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = open(os.path.join(root, 'converter', 'convert.lua'), 'rb').read().replace(b'\r\n', b'\n')
lines = ['// Generated by tools/embed_converter.py from converter/convert.lua. Do not edit.']
for i in range(0, len(data), 24):
    lines.append(','.join(str(b) for b in data[i:i + 24]) + ',')
open(os.path.join(root, 'native', 'src', 'convert_lua.inc'), 'w', newline='\n').write('\n'.join(lines) + '\n')
print('convert_lua.inc:', len(data), 'bytes')
