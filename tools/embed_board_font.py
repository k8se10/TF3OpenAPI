"""Writes the departure boards' dot font as a C++ table for the native layer.

    python tools/embed_board_font.py

Reads tools/board_font.py (the same table the board's shipped picture is drawn with) and writes
native/src/board_font.inc: for each character from space to '~', five columns, lowest bit at the top.
Run it again after any change to the font.
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import board_font  # noqa: E402


def main():
    lines = ['// Generated by tools/embed_board_font.py from tools/board_font.py - do not edit.',
             '// kBoardFont[c - 32]: five columns of a 5 x 7 character, lowest bit at the top.']
    for code in range(32, 127):
        text = board_font._TABLE.get(chr(code), board_font._TABLE['?'])
        columns = ', '.join('0x%s' % text[i:i + 2] for i in range(0, 10, 2))
        name = chr(code) if chr(code) not in ('\\',) else 'backslash'
        lines.append('{ %s },  // %s' % (columns, name))
    out = os.path.join(here, '..', 'native', 'src', 'board_font.inc')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('board_font.inc: %d characters, height %d, gap %d, space %d' % (95, board_font.HEIGHT, board_font.GAP, board_font.SPACE))


if __name__ == '__main__':
    main()
