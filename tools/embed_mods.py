"""Packs this project's own mods (mod/tf3api_*) into native/src/own_mods.inc, for the DLL to carry.

At launch the DLL writes them out as ordinary files to %LOCALAPPDATA%\\TF3OpenAPI\\mods\\<mod id>\\ and the game's
mod scan is pointed at that folder as one more source ("TF3OpenAPI"). The packed form is a list of files, each
compressed on its own with deflate (no extra dependencies in the DLL beyond a small inflate).

Layout of the blob (little endian):
    "TF3M" u32 file count
    per file: u16 name length, name (UTF-8, mod id first, '/' separators), u32 raw size, u32 packed size,
              u32 crc32 of the raw bytes, packed bytes (raw deflate)

The generated native/src/own_mods.inc is large and is not committed: run this after changing a mod
(and after tools/build_boards.py, whose screen pictures are the bulk of it), before building the DLL:
    python tools/embed_mods.py
"""
import os
import struct
import zlib

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
mods = os.path.join(root, 'mod')

entries = []
for mod in sorted(os.listdir(mods)):
    folder = os.path.join(mods, mod)
    if not mod.startswith('tf3api_') or not os.path.isdir(folder):
        continue
    for base, dirs, files in os.walk(folder):
        dirs.sort()
        for name in sorted(files):
            path = os.path.join(base, name)
            rel = mod + '/' + os.path.relpath(path, folder).replace(os.sep, '/')
            raw = open(path, 'rb').read()
            packer = zlib.compressobj(9, zlib.DEFLATED, -15)
            packed = packer.compress(raw) + packer.flush()
            entries.append((rel, raw, packed))

blob = bytearray(b'TF3M' + struct.pack('<I', len(entries)))
for rel, raw, packed in entries:
    name = rel.encode('utf-8')
    blob += struct.pack('<H', len(name)) + name
    blob += struct.pack('<III', len(raw), len(packed), zlib.crc32(raw) & 0xFFFFFFFF) + packed

lines = ['// Generated by tools/embed_mods.py from mod/tf3api_*. Do not edit; not committed.']
for i in range(0, len(blob), 32):
    lines.append(','.join(str(b) for b in blob[i:i + 32]) + ',')
with open(os.path.join(root, 'native', 'src', 'own_mods.inc'), 'w', newline='\n') as out:
    out.write('\n'.join(lines) + '\n')
print('own_mods.inc: %d files, %d bytes packed (from %d)' % (len(entries), len(blob), sum(len(r) for _n, r, _p in entries)))
