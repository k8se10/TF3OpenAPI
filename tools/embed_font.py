"""Writes native/third_party/isotherm_sans/IsothermSans-Bold.ttf into native/src/isotherm_sans_bold.inc as a byte
array, so that the native layer carries the font (the converter writes it into remastered mods whose labels use it).

Isotherm Sans (c) its author, SIL Open Font License 1.1 (native/third_party/isotherm_sans/OFL.txt).
Run from the repository root after changing the font:
    python tools/embed_font.py
"""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = open(os.path.join(root, 'native', 'third_party', 'isotherm_sans', 'IsothermSans-Bold.ttf'), 'rb').read()
lines = ['// Generated by tools/embed_font.py from native/third_party/isotherm_sans/IsothermSans-Bold.ttf. Do not edit.']
for i in range(0, len(data), 24):
    lines.append(','.join(str(b) for b in data[i:i + 24]) + ',')
open(os.path.join(root, 'native', 'src', 'isotherm_sans_bold.inc'), 'w', newline='\n').write('\n'.join(lines) + '\n')
print('isotherm_sans_bold.inc:', len(data), 'bytes')
