"""Writes tools/splash/logo.png (512 x 512, made from the project logo) into native/src/splash_logo.inc as raw
RGBA bytes, so the native layer can show it on the game's splash screen after the Paradox logo (native/src/splash.cpp).
Run from the repository root after changing the logo:   python tools/embed_splash.py
Needs: pip install pillow
"""
import os
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
img = Image.open(os.path.join(root, 'tools', 'splash', 'logo.png')).convert('RGBA')
assert img.size == (512, 512), img.size
data = img.tobytes()
lines = ['// Generated by tools/embed_splash.py from tools/splash/logo.png: 512 x 512 RGBA. Do not edit.']
for i in range(0, len(data), 32):
    lines.append(','.join(str(b) for b in data[i:i + 32]) + ',')
open(os.path.join(root, 'native', 'src', 'splash_logo.inc'), 'w', newline='\n').write('\n'.join(lines) + '\n')
print('splash_logo.inc:', len(data), 'bytes')
